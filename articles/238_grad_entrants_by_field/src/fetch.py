"""data/raw/ の Excel を e-Stat から取り直す（記事の作成時は同じ URL から取得した）。
文部科学省「学校基本調査」の各年度の高等教育機関・専修学校の表。statInfId は下の IDS。
使い方：python fetch.py（ネットにつながる環境で）"""
import time, requests
from common import RAW
U = "https://www.e-stat.go.jp/stat-search/file-download?statInfId={}&fileKind=0"
IDS = {
    (2000, 'N'): "000015170578",
    (2001, 'N'): "000012663129",
    (2002, 'N'): "000012459909",
    (2003, 'N'): "000006499300",
    (2004, 'N'): "000002947524",
    (2005, 'N'): "000002947037",
    (2006, 'N'): "000001226017",
    (2007, 'N'): "000001211199",
    (2008, 'N'): "000002031011",
    (2009, 'N'): "000006196996",
    (2010, 'N'): "000008349977",
    (2011, 'N'): "000012683853",
    (2012, 'N'): "000018428750",
    (2013, 'N'): "000023610155",
    (2014, 'N'): "000027597245",
    (2015, 'N'): "000031358101",
    (2016, 'N'): "000031504870",
    (2017, 'N'): "000031656043",
    (2018, 'N'): "000031776665",
    (2019, 'N'): "000031894025",
    (2020, 'N'): "000032040276",
    (2021, 'N'): "000032155540",
    (2022, 'N'): "000032265035",
    (2023, 'N'): "000040128623",
    (2024, 'N'): "000040230326",
    (2025, 'N'): "000040392737",
}


def main():
    RAW.mkdir(parents=True, exist_ok=True)
    for (y, t), sid in sorted(IDS.items()):
        b = requests.get(U.format(sid), timeout=120).content
        ext = "xlsx" if b[:2] == b"PK" else "xls"
        (RAW / f"{y}_{t}_{sid}.{ext}").write_bytes(b)
        time.sleep(1)


if __name__ == "__main__":
    main()

"""data/raw/ の Excel を e-Stat から取り直す（記事の作成時は同じ URL から取得した）。
文部科学省「学校基本調査」の各年度の高等教育機関・専修学校の表。statInfId は下の IDS。
使い方：python fetch.py（ネットにつながる環境で）"""
import time, requests
from common import RAW
U = "https://www.e-stat.go.jp/stat-search/file-download?statInfId={}&fileKind=0"
IDS = {
    (2000, 'GU'): "000015170567",
    (2001, 'GU'): "000012663118",
    (2002, 'GU'): "000012459898",
    (2003, 'GU'): "000006499289",
    (2004, 'GU'): "000002947513",
    (2005, 'GU'): "000002947026",
    (2006, 'GU'): "000001226006",
    (2007, 'GU'): "000001211188",
    (2008, 'GU'): "000002031000",
    (2009, 'GU'): "000006196985",
    (2010, 'GU'): "000008349966",
    (2011, 'GU'): "000012683842",
    (2012, 'GU'): "000018428741",
    (2013, 'GU'): "000023610146",
    (2014, 'GU'): "000027597236",
    (2015, 'GU'): "000031357773",
    (2016, 'GU'): "000031504862",
    (2017, 'GU'): "000031656035",
    (2018, 'GU'): "000031776657",
    (2019, 'GU'): "000031894017",
    (2020, 'GU'): "000032040268",
    (2021, 'GU'): "000032155512",
    (2022, 'GU'): "000032265027",
    (2023, 'GU'): "000040128615",
    (2024, 'GU'): "000040230298",
    (2025, 'GU'): "000040392729",
}


def main():
    RAW.mkdir(parents=True, exist_ok=True)
    for (y, t), sid in sorted(IDS.items()):
        b = requests.get(U.format(sid), timeout=120).content
        ext = "xlsx" if b[:2] == b"PK" else "xls"
        (RAW / f"{y}_{t}_{sid}.{ext}").write_bytes(b)
        time.sleep(1)


if __name__ == "__main__":
    main()

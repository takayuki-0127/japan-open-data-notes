def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
        return r.read()


def main():
    RAW.mkdir(parents=True, exist_ok=True)
    lines = ["# SOURCES（元データの取得元）", "", f"取得日：{datetime.date.today().isoformat()}（01_fetch.py で取得）", "",
             "| ファイル | 地点（地域） | URL | sha256 の先頭12字（gzip を解いた中身） |", "|---|---|---|---|"]
    meta = ["station,prec_no,block_no,region,order"]
    for i, (name, prec, block, reg) in enumerate(STATIONS):
        url = A1.format(prec, block)
        b = get(url)
        fn = f"jma_a1_{block}.html.gz"
        (RAW / fn).write_bytes(gzip.compress(b, mtime=0))
        lines.append(f"| {fn} | {name}（{reg}） | {url} | {hashlib.sha256(b).hexdigest()[:12]} |")
        meta.append(f"{name},{prec},{block},{reg},{i}")
        time.sleep(1.0)
    (RAW / "stations.csv").write_text("\n".join(meta) + "\n", encoding="utf-8")
    lines += ["", "出典：気象庁「過去の気象データ検索」年ごとの値（https://www.data.jma.go.jp/stats/etrn/index.php）。",
              "地点の一覧：気象庁「日本の年降水量偏差の算出方法」（https://www.data.jma.go.jp/cpdinfo/temp/clc_jpn_r.html）の51地点。",
              "地域の区分は気象庁の天候の区分（北日本・東日本・西日本・沖縄奄美）に合わせた（作成者が地点ごとに割り当て）。"]
    (RAW / "SOURCES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()

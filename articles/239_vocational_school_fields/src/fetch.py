"""data/raw/ の Excel を e-Stat から取り直す（記事の作成時は同じ URL から取得した）。
文部科学省「学校基本調査」の各年度の高等教育機関・専修学校の表。statInfId は下の IDS。
使い方：python fetch.py（ネットにつながる環境で）"""
import time, requests
from common import RAW
U = "https://www.e-stat.go.jp/stat-search/file-download?statInfId={}&fileKind=0"
IDS = {
    (2000, 'S'): "000015170443",
    (2001, 'S'): "000012662990",
    (2002, 'S'): "000012459770",
    (2003, 'S'): "000006499161",
    (2004, 'S'): "000002947385",
    (2005, 'S'): "000002946898",
    (2006, 'S'): "000001228131",
    (2007, 'S'): "000001191486",
    (2008, 'S'): "000002030898",
    (2009, 'S'): "000006196883",
    (2010, 'S'): "000008349864",
    (2011, 'S'): "000012683740",
    (2012, 'S'): "000018428640",
    (2013, 'S'): "000023610045",
    (2014, 'S'): "000027597135",
    (2015, 'S'): "000031358003",
    (2016, 'S'): "000031504761",
    (2017, 'S'): "000031656862",
    (2018, 'S'): "000031776547",
    (2019, 'S'): "000031893907",
    (2020, 'S'): "000032040615",
    (2021, 'S'): "000032156084",
    (2022, 'S'): "000032264917",
    (2023, 'S'): "000040128370",
    (2024, 'S'): "000040230666",
    (2025, 'S'): "000040393885",
}


def main():
    RAW.mkdir(parents=True, exist_ok=True)
    for (y, t), sid in sorted(IDS.items()):
        b = requests.get(U.format(sid), timeout=120).content
        ext = "xlsx" if b[:2] == b"PK" else "xls"
        (RAW / f"{y}_{t}_{sid}.{ext}").write_bytes(b)
        time.sleep(1)


if __name__ == "__main__":
    main()

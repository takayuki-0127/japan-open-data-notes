"""data/raw/ の Excel を e-Stat から取り直す（記事の作成時は同じ URL から取得した）。
文部科学省「学校基本調査」の各年度の高等教育機関・専修学校の表。statInfId は下の IDS。
使い方：python fetch.py（ネットにつながる環境で）"""
import time, requests
from common import RAW
U = "https://www.e-stat.go.jp/stat-search/file-download?statInfId={}&fileKind=0"
IDS = {
    (2000, 'GJ'): "000015170598",
    (2001, 'GJ'): "000012663149",
    (2002, 'GJ'): "000012459929",
    (2003, 'GJ'): "000006499320",
    (2004, 'GJ'): "000002947544",
    (2005, 'GJ'): "000002947057",
    (2006, 'GJ'): "000001226037",
    (2007, 'GJ'): "000001211219",
    (2008, 'GJ'): "000002031031",
    (2009, 'GJ'): "000006197016",
    (2010, 'GJ'): "000008349997",
    (2011, 'GJ'): "000012683873",
    (2012, 'GJ'): "000018428770",
    (2013, 'GJ'): "000023610175",
    (2014, 'GJ'): "000027597265",
    (2015, 'GJ'): "000031358121",
    (2016, 'GJ'): "000031504890",
    (2017, 'GJ'): "000031656063",
    (2018, 'GJ'): "000031776685",
    (2019, 'GJ'): "000031894045",
    (2020, 'GJ'): "000032040296",
    (2021, 'GJ'): "000032155560",
    (2022, 'GJ'): "000032265055",
    (2023, 'GJ'): "000040128650",
    (2024, 'GJ'): "000040230346",
    (2025, 'GJ'): "000040392977",
}


def main():
    RAW.mkdir(parents=True, exist_ok=True)
    for (y, t), sid in sorted(IDS.items()):
        b = requests.get(U.format(sid), timeout=120).content
        ext = "xlsx" if b[:2] == b"PK" else "xls"
        (RAW / f"{y}_{t}_{sid}.{ext}").write_bytes(b)
        time.sleep(1)


if __name__ == "__main__":
    main()

"""01 取得：総務省「国勢調査」の「労働力状態，年齢（各歳），男女別15歳以上人口」の表を e-Stat から取る。
政府のサイトはこの環境のスクリプトから届かないことがあるため、ブラウザ（e-Stat のページ内の fetch と SheetJS）で読み、
data/raw/ に JSON で置いた。手元で取り直す場合は、下の URL を開くとファイルが落ちる（fileKind は Excel=0, CSV=1）。

| 年 | 表 | statInfId | 形式 |
|---|---|---|---|
| 2000 | 第2次基本集計 第1表 労働力状態（8区分），年齢（各歳），男女別15歳以上人口－全国 | 000000031852 | Excel |
| 2005 | 第2次基本集計 第1表（同） | 000000038461 | Excel |
| 2010 | 産業等基本集計 第1-1表（同）－全国，都道府県 | 000012989686 | CSV |
| 2015 | 就業状態等基本集計 第1-1表（同，総数及び日本人）－全国，都道府県… | 000031569350 | CSV |
| 2020 | 就業状態等基本集計 第1-1表 男女，年齢（各歳），国籍総数か日本人，労働力状態別人口－全国，都道府県… | 000032201174 | Excel |

data/raw/f31_census_lfs.json      … 2000〜2015年の表（シートをそのまま2次元配列に）
data/raw/f31_census2020_pref.json … 2020年の表のうち全国と47都道府県・国籍総数の行
"""
from common import RAW
URL = "https://www.e-stat.go.jp/stat-search/file-download?statInfId={id}&fileKind={k}"
IDS = {2000: ("000000031852", 0), 2005: ("000000038461", 0), 2010: ("000012989686", 1),
       2015: ("000031569350", 1), 2020: ("000032201174", 0)}
if __name__ == "__main__":
    for y, (i, k) in IDS.items():
        print(y, URL.format(id=i, k=k))
    for f in ["f31_census_lfs.json", "f31_census2020_pref.json"]:
        print(f, (RAW / f).exists())

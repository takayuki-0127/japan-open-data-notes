NENJI = []


def fetch(sid):
    req = urllib.request.Request(BASE.format(sid), headers={"User-Agent": "open-data-notes-fetch"})
    with urllib.request.urlopen(req, timeout=120) as r:
        return r.read()


def main():
    RAW.mkdir(parents=True, exist_ok=True)
    lines = ["# SOURCES（元データの取得元）", "", f"取得日：{datetime.date.today().isoformat()}（01_fetch.py で取得）", "",
             "| ファイル | 調査年 | 中身 | URL | sha256 の先頭12字 |", "|---|---|---|---|---|"]
    items = [(f"{k}_{key}_{y}", y, sid, t) for y, k, key, sid, t in FILES] + [(n, "-", sid, t) for n, sid, t in NENJI]
    for name, y, sid, title in items:
        b = fetch(sid)
        ext = ".xlsx" if b[:2] == b"PK" else ".xls"
        (RAW / (name + ext)).write_bytes(b)
        lines.append(f"| {name}{ext} | {y} | {title} | {BASE.format(sid)} | {hashlib.sha256(b).hexdigest()[:12]} |")
        time.sleep(0.5)
    lines += ["", "出典：文部科学省「学校基本調査」（e-Stat https://www.e-stat.go.jp/stat-search/files?toukei=00400001&tstat=000001011528）。",
              "各年5月1日時点。es は小学校、jh は中学校。classes＝編制方式別学級数、pupils＝学級編制方式別児童（生徒）数、sizebins＝収容人員別学級数。"]
    (RAW / "SOURCES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()

def fetch(sid):
    for kind in (1, 0):
        req = urllib.request.Request(URL.format(sid, kind), headers={"User-Agent": "open-data-notes-fetch"})
        with urllib.request.urlopen(req, timeout=120) as r:
            b = r.read()
        if not b.lstrip()[:15].lower().startswith((b"<!doctype", b"<html")):
            ext = ".xlsx" if b[:2] == b"PK" else (".xls" if b[:4] == b"\xd0\xcf\x11\xe0" else ".csv")
            return b, ext, kind
    raise RuntimeError(sid)


def main():
    RAW.mkdir(parents=True, exist_ok=True)
    lines = ["# SOURCES（元データの取得元）", "", f"取得日：{datetime.date.today().isoformat()}（01_fetch.py で取得）", "",
             "| ファイル | 調査年 | 中身（e-Stat の表題） | URL | sha256 の先頭12字 |", "|---|---|---|---|---|"]
    for year, kind, sid, desc in FILES:
        b, ext, fk = fetch(sid)
        name = f"y{year}_{kind}_{sid}{ext}"
        (RAW / name).write_bytes(b)
        lines.append(f"| {name} | {year} | {desc} | {URL.format(sid, fk)} | {hashlib.sha256(b).hexdigest()[:12]} |")
        time.sleep(0.5)
    lines += ["", "出典：総務省「通信利用動向調査」世帯構成員編（e-Stat https://www.e-stat.go.jp/stat-search/files?toukei=00200356）。",
              "調査年の表記は調査を行った年（各年の調査時点は年によって異なり、おおむね8月末〜翌年1月）。"]
    (RAW / "SOURCES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()

def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "research-script"})
    with urllib.request.urlopen(req, timeout=180) as r:
        return r.read()

def main():
    RAW.mkdir(parents=True, exist_ok=True)
    today = datetime.date.today().isoformat()
    lines = ["# 元データの出典（取得日と URL）", "", "| ファイル | 中身 | 系列数または URL | 取得日 |", "|---|---|---|---|"]
    for name, codes in SETS.items():
        url = BOJ.format(codes=",".join(codes))
        b = get(url); j = json.loads(b)
        assert j.get("STATUS") == 200, j.get("MESSAGE")
        assert j.get("NEXTPOSITION") is None, "続きがある"
        (RAW / name).write_bytes(b)
        lines.append(f"| {name} | 日本銀行 都道府県別預金・現金・貸出金（MD12） | {len(codes)} | {today} |")
        print("saved", name, len(j["RESULTSET"]))
    # 照らし合わせ用：日本銀行サイトの公表資料（2026年3月末、Excel）
    xurl = "https://www.boj.or.jp/statistics/dl/depo/pref/pre2603.xlsx"
    (RAW / "boj_pref_pre2603.xlsx").write_bytes(get(xurl))
    lines.append(f"| boj_pref_pre2603.xlsx | 日本銀行「都道府県別預金・現金・貸出金（国内銀行）＜2026年3月末＞」公表資料（照らし合わせ用） | {xurl} | {today} |")
    lines += ["", "- 取得の URL の形：" + BOJ.replace("{codes}", "<系列コードをカンマでつないだもの（01_fetch.py の SETS）>"),
              "- 日本銀行 時系列統計データ検索サイト：https://www.stat-search.boj.or.jp/ （API 利用）",
              "- 出典を示して加工して使う（日本銀行の利用規約）。"]
    (RAW / "SOURCES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

if __name__ == "__main__":
    main()

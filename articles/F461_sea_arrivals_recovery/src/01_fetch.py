def main():
    RAW.mkdir(parents=True, exist_ok=True)
    today = datetime.date.today().isoformat()
    lines = ["# 元データの出典（取得日と URL）", "", f"取得日：{today}（01_fetch.py で取得）", "",
             "| ファイル | 中身 | URL | sha256 の先頭12字（元のファイル） |", "|---|---|---|---|"]
    for name, (sid, kind, title) in FILES.items():
        url = BASE.format(sid, kind)
        with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=180) as r:
            b = r.read()
        if b[:2] == b"PK":
            fn = f"{name}.xlsx"; (RAW / fn).write_bytes(b)
        else:
            fn = f"{name}.xls.gz"
            with open(RAW / fn, "wb") as fo:
                with gzip.GzipFile(filename="", mode="wb", fileobj=fo, mtime=0) as g:
                    g.write(b)
        lines.append(f"| {fn} | {name.split('_')[1]}年 出入国管理統計 {title} | {url} | {hashlib.sha256(b).hexdigest()[:12]} |")
        print("saved", fn, len(b), flush=True)
    lines += ["", "- 統計表の一覧：https://www.e-stat.go.jp/stat-search/files?toukei=00250011&tstat=000001012480",
              "- 出典：法務省「出入国管理統計」（政府統計の総合窓口 e-Stat）。政府標準利用規約（第2.0版）に従い、出典を示して加工して使う。",
              "- .xls.gz は、元の .xls を gzip で圧縮したもの（中身は同じ。02_build.py が展開して読む）。"]
    (RAW / "SOURCES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()

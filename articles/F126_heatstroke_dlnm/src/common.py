def block(p):
    if p == 1: return "北海道"
    if p <= 7: return "東北"
    if p <= 14: return "関東"
    if p <= 23: return "中部"
    if p <= 30: return "近畿"
    if p <= 35: return "中国"
    if p <= 39: return "四国"

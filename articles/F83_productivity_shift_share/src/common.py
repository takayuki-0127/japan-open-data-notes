def norm(s: str) -> str:
    """'３．製　造　業' や '　　（１）食　料　品' から産業名だけ取り出す"""
    s = s.replace("　", "").replace(" ", "")
    s = re.sub(r"^[０-９0-9]+[．.]", "", s)
    s = re.sub(r"^[（(][０-９0-9]+[）)]", "", s)
    return s


def num(x: str):
    x = x.replace(",", "").strip()
    try:
        return float(x)
    except ValueError:
        return None
